function question([prompt, correct, ...wrong], offset) {
    const choices = [correct, ...wrong];
    const answer = offset % 4;
    for (let i = 0; i < answer; i++) choices.unshift(choices.pop());
    return {
        question: prompt,
        choices,
        answer,
        explanation: `${correct}. Revisit the worked steps and verify the result in a practice workbook.`,
    };
}
